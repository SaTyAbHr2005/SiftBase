"""Download the site's Poly Haven assets (CC0) once, shrink them and write web/public/assets.

python scripts/prepare_assets.py
Also generates the tileable caustic light. Sizes and sources are listed in DESIGN.md section 7.
"""
import tempfile
import urllib.request
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

OUT=Path(__file__).resolve().parent.parent/"web"/"public"/"assets"
DL="https://dl.polyhaven.org/file/ph-assets"
# (published name, source url, Poly Haven page, author, size, webp quality)
TEXTURES=[
    ("riverbed-color.webp",f"{DL}/Textures/jpg/1k/ganges_river_pebbles/ganges_river_pebbles_diff_1k.jpg","ganges_river_pebbles","Amal Kumar",512,72),
    ("riverbed-normal.webp",f"{DL}/Textures/jpg/1k/ganges_river_pebbles/ganges_river_pebbles_nor_gl_1k.jpg","ganges_river_pebbles","Amal Kumar",512,70),
    ("riverbed-rough.webp",f"{DL}/Textures/jpg/1k/ganges_river_pebbles/ganges_river_pebbles_rough_1k.jpg","ganges_river_pebbles","Amal Kumar",512,60),
    ("pan-normal.webp",f"{DL}/Textures/jpg/1k/metal_plate_02/metal_plate_02_nor_gl_1k.jpg","metal_plate_02","Rob Tuytel",512,70),
    ("pan-rough.webp",f"{DL}/Textures/jpg/1k/metal_plate_02/metal_plate_02_rough_1k.jpg","metal_plate_02","Rob Tuytel",512,60),
]
HDRI=("river.hdr",f"{DL}/HDRIs/hdr/1k/blau_river_1k.hdr","blau_river","Andreas Mischok",(256,128))


def fetch(url,tmp):
    path=Path(tmp)/url.rsplit("/",1)[1]
    req=urllib.request.Request(url,headers={"User-Agent":"siftbase-assets"})
    with urllib.request.urlopen(req,timeout=60) as r:
        path.write_bytes(r.read())
    return path


def caustic(size=256):
    # Sines on whole periods of the tile, so the pattern repeats without a seam.
    y,x=np.mgrid[0:size,0:size]/size*2*np.pi
    v=np.zeros((size,size))
    for a,b,p in [(3,1,0.0),(1,4,1.3),(5,-2,2.1),(-2,3,0.7),(4,5,2.9)]:
        v+=np.sin(a*x+b*y+p+1.5*np.sin(b*x-a*y))
    v=1-np.abs(v)/v.__abs__().max()
    return Image.fromarray((np.clip(v,0,1)**6*255).astype(np.uint8),"L")


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    rows=[]
    with tempfile.TemporaryDirectory() as tmp:
        for name,url,page,author,size,q in TEXTURES:
            img=Image.open(fetch(url,tmp)).convert("RGB").resize((size,size),Image.LANCZOS)
            img.save(OUT/name,"WEBP",quality=q,method=6)
            rows.append((name,page,author,f"1K JPG to {size}px WebP q{q}"))
        name,url,page,author,(w,h)=HDRI
        hdr=cv2.imread(str(fetch(url,tmp)),cv2.IMREAD_ANYDEPTH|cv2.IMREAD_COLOR)
        cv2.imwrite(str(OUT/name),cv2.resize(hdr,(w,h),interpolation=cv2.INTER_AREA))
        rows.append((name,page,author,f"1K HDR to {w}x{h}"))
    caustic().save(OUT/"caustic.webp","WEBP",quality=70,method=6)
    lines=["# Asset sources","","Scanned assets from [Poly Haven](https://polyhaven.com), licensed CC0 (https://polyhaven.com/license).",
           "Regenerate every file with `python scripts/prepare_assets.py`.","",
           "| File | Source | Author | Resize | Size |","|---|---|---|---|---|"]
    for name,page,author,how in rows:
        lines.append(f"| {name} | https://polyhaven.com/a/{page} | {author} | {how} | {(OUT/name).stat().st_size//1024} KB |")
    lines.append(f"| caustic.webp | generated by the script | none | 256px tile | {(OUT/'caustic.webp').stat().st_size//1024} KB |")
    (OUT/"SOURCES.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    total=sum(f.stat().st_size for f in OUT.iterdir() if f.suffix!=".md")
    print("\n".join(lines[-len(rows)-1:]),f"\ntotal {total//1024} KB")


if __name__=="__main__":
    main()
